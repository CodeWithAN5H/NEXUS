import 'dart:io';

import 'package:drift/drift.dart' show driftRuntimeOptions;
import 'package:drift/native.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:nexus/core/errors/app_failure.dart';
import 'package:nexus/data/database/nexus_database.dart';
import 'package:nexus/data/models/anime.dart';
import 'package:nexus/data/models/app_settings.dart';
import 'package:nexus/data/models/library.dart';
import 'package:nexus/data/repositories/history_repository.dart';
import 'package:nexus/data/repositories/library_repository.dart';
import 'package:nexus/data/repositories/preferences_repository.dart';
import 'package:nexus/data/repositories/provider_store.dart';
import 'package:nexus/integrations/providers/provider_record.dart';

import 'support/fake_providers.dart';

const Anime _frieren = Anime(
  id: 154587,
  title: "Frieren: Beyond Journey's End",
);

const Anime _newTitle = Anime(id: 42, title: 'A Newly Saved Title');

/// The committed v1 database, generated by v0.1.0-alpha and never regenerated.
const String _fixturePath = 'test/fixtures/nexus_v1.sqlite';

Future<File> _copyFixture(Directory dir) async {
  final File fixture = File(_fixturePath);
  expect(
    await fixture.exists(),
    isTrue,
    reason: 'the v1 fixture must be committed, not generated per run',
  );
  return fixture.copy('${dir.path}/nexus.sqlite');
}

Future<int> _pragmaInt(NexusDatabase db, String pragma, String column) {
  return db
      .customSelect(pragma)
      .map((dynamic row) => row.read<int>(column) as int)
      .getSingle();
}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  driftRuntimeOptions.dontWarnAboutMultipleDatabases = true;

  group('T-P01 migration 1 → 2 from a real v1 file', () {
    late Directory dir;
    late NexusDatabase db;

    setUp(() async {
      dir = await Directory.systemTemp.createTemp('nexus-v1-migration');
      db = NexusDatabase(NativeDatabase(await _copyFixture(dir)));
    });

    tearDown(() async {
      await db.close();
      await dir.delete(recursive: true);
    });

    test('creates the three provider tables and bumps user_version', () async {
      expect(db.schemaVersion, 2);
      expect(await db.select(db.providerEntries).get(), isNotNull);
      expect(await db.select(db.providerTitlePrefs).get(), isNotNull);
      expect(await db.select(db.providerManifests).get(), isNotNull);
      expect(await _pragmaInt(db, 'PRAGMA user_version', 'user_version'), 2);
      expect(
        await _pragmaInt(db, 'PRAGMA foreign_keys', 'foreign_keys'),
        1,
        reason: 'referential integrity stays enforced after the upgrade',
      );
    });

    test(
      'keeps library, progress, settings and search history intact',
      () async {
        final LibraryEntry? entry = await LibraryRepository(db)
            .entryFor(154587);
        expect(entry?.title, _frieren.title);
        expect(entry?.watchedEpisodes, 7);
        expect(entry?.totalEpisodes, 28);
        expect(entry?.status, LibraryStatus.watching);

        final WatchProgress? progress = await HistoryRepository(db)
            .progressFor(154587, 7);
        expect(progress?.position, const Duration(minutes: 7, seconds: 12));
        expect(progress?.duration, const Duration(minutes: 24));
        expect(progress?.providerId, 'sample');
        expect(progress?.seriesId, 'frieren');

        final AppSettings settings = await PreferencesRepository(db).load();
        expect(settings.autoplayNext, isFalse);
        expect(settings.preferredQualityHeight, 720);
        expect(settings.subtitleSize, SubtitleSize.large);
        expect(settings.preferredAudioLanguage, 'ja');
        expect(settings.gridDensity, GridDensity.compact);
        expect(settings.reduceMotion, isTrue);
        expect(settings.enabledProviderIds, <String>{'sample'});

        final List<SearchRow> searches = await db
            .select(db.recentSearches)
            .get();
        expect(searches, hasLength(2));
      },
    );

    test('backfills provider_entries from sources.enabled', () async {
      final List<ProviderEntryRow> rows = await db
          .select(db.providerEntries)
          .get();
      expect(rows, hasLength(1));
      expect(rows.single.providerId, 'sample');
      expect(rows.single.origin, 'builtIn');
      expect(rows.single.enabled, isTrue);
      expect(rows.single.priority, 0);
    });
  });

  group('T-P02 migration is re-runnable', () {
    test('reopening an upgraded file does not duplicate rows', () async {
      final Directory dir = await Directory.systemTemp.createTemp('nexus-v2');
      final File file = await _copyFixture(dir);

      final NexusDatabase first = NexusDatabase(NativeDatabase(file));
      expect((await first.select(first.providerEntries).get()), hasLength(1));
      await first.close();

      final NexusDatabase second = NexusDatabase(NativeDatabase(file));
      expect(second.schemaVersion, 2);
      expect((await second.select(second.providerEntries).get()), hasLength(1));
      expect(
        (await LibraryRepository(second).entryFor(154587))?.watchedEpisodes,
        7,
      );
      await second.close();
      await dir.delete(recursive: true);
    });
  });

  group('T-P03 / T-P04 / T-P05 persistence across restarts', () {
    test('installed providers, order and title preference survive', () async {
      final Directory dir = await Directory.systemTemp.createTemp(
        'nexus-store',
      );
      final File file = File('${dir.path}/nexus.sqlite');

      final NexusDatabase first = NexusDatabase(NativeDatabase(file));
      final ProviderStore store = ProviderStore(first);
      await store.syncBuiltIns(
        <FakeStreamingProvider>[
          FakeStreamingProvider(id: 'a'),
          FakeStreamingProvider(id: 'b'),
        ],
        enabledIds: <String>{'a', 'b'},
      );
      await store.setPriority(<String>['b', 'a']);
      await store.setEnabled('b', false);
      await store.setPreference(154587, 'b');
      expect(await store.manifestJsonFor('a'), isNull);
      await store.saveManifest(
        providerId: 'a',
        manifestJson: '{"manifestVersion":1}',
        sourceUrl: 'https://example.test/manifest.json',
      );
      await first.close();

      final NexusDatabase second = NexusDatabase(NativeDatabase(file));
      final ProviderStore reopened = ProviderStore(second);
      final List<ProviderRecord> records = await reopened.loadAll();
      expect(records.map((ProviderRecord r) => r.providerId), <String>[
        'b',
        'a',
      ]);
      expect(records.first.enabled, isFalse);
      expect(records.last.enabled, isTrue);
      expect(await reopened.preferenceFor(154587), 'b');
      expect(await reopened.manifestJsonFor('a'), '{"manifestVersion":1}');
      await second.close();
      await dir.delete(recursive: true);
    });
  });

  group('provider churn never damages user data (T-P10)', () {
    test(
      'removing a provider leaves library, history and settings alone',
      () async {
        final NexusDatabase db = NexusDatabase(NativeDatabase.memory());
        final LibraryRepository library = LibraryRepository(db);
        final HistoryRepository history = HistoryRepository(db);
        final ProviderStore store = ProviderStore(db);

        await library.save(_newTitle, status: LibraryStatus.watching);
        await library.markEpisodeWatched(42, 3, totalEpisodes: 12);
        await history.record(
          animeId: 42,
          episodeNumber: 3,
          title: _newTitle.title,
          position: const Duration(minutes: 5),
          duration: const Duration(minutes: 24),
          providerId: 'a',
          seriesId: 'a-series',
        );
        await PreferencesRepository(db)
            .save(const AppSettings(preferredQualityHeight: 480));

        await store.syncBuiltIns(
          <FakeStreamingProvider>[
            FakeStreamingProvider(id: 'a'),
            FakeStreamingProvider(id: 'b'),
          ],
          enabledIds: <String>{'a', 'b'},
        );
        await store.setPreference(42, 'a');
        await store.saveManifest(
          providerId: 'a',
          manifestJson: '{"manifestVersion":1}',
        );

        await store.remove('a');

        expect(
          (await store.loadAll()).map((ProviderRecord r) => r.providerId),
          <String>['b'],
        );
        expect(await store.preferenceFor(42), isNull);
        expect(await store.manifestJsonFor('a'), isNull);

        expect((await library.entryFor(42))?.watchedEpisodes, 3);
        expect(
          (await history.progressFor(42, 3))?.position,
          const Duration(minutes: 5),
        );
        expect(
          (await PreferencesRepository(db).load()).preferredQualityHeight,
          480,
        );

        await db.close();
      },
    );

    test('disabling keeps the row and its configuration', () async {
      final NexusDatabase db = NexusDatabase(NativeDatabase.memory());
      final ProviderStore store = ProviderStore(db);
      await store.syncBuiltIns(
        <FakeStreamingProvider>[FakeStreamingProvider(id: 'a')],
        enabledIds: <String>{'a'},
      );
      await store.setEnabled('a', false);
      final ProviderRecord record = (await store.loadAll()).single;
      expect(record.enabled, isFalse);
      expect(record.config, isEmpty);
      await db.close();
    });
  });

  group('manifest storage guards', () {
    test('a manifest over 512 KiB is refused before it is stored', () async {
      final NexusDatabase db = NexusDatabase(NativeDatabase.memory());
      final ProviderStore store = ProviderStore(db);
      final String oversized = List<String>.filled(
        ProviderStore.maxManifestBytes + 1,
        'x',
      ).join();
      await expectLater(
        store.saveManifest(providerId: 'a', manifestJson: oversized),
        throwsA(isA<StorageFailure>()),
      );
      expect(await store.manifestJsonFor('a'), isNull);
      await db.close();
    });
  });

  group('T-P11 data preservation across an app update', () {
    test('v1 data plus new data survive the upgrade and a reopen', () async {
      final Directory dir = await Directory.systemTemp.createTemp('nexus-p11');
      final File file = await _copyFixture(dir);

      final NexusDatabase upgraded = NexusDatabase(NativeDatabase(file));
      await LibraryRepository(upgraded)
          .save(_newTitle, status: LibraryStatus.completed);
      await HistoryRepository(upgraded).record(
        animeId: 42,
        episodeNumber: 12,
        title: _newTitle.title,
        position: const Duration(minutes: 20),
        duration: const Duration(minutes: 24),
      );
      await upgraded.close();

      final NexusDatabase reopened = NexusDatabase(NativeDatabase(file));
      expect(
        (await LibraryRepository(reopened).entryFor(154587))?.watchedEpisodes,
        7,
      );
      expect(
        (await LibraryRepository(reopened).entryFor(42))?.status,
        LibraryStatus.completed,
      );
      expect(
        (await HistoryRepository(reopened).progressFor(154587, 7))?.position,
        const Duration(minutes: 7, seconds: 12),
      );
      expect(
        (await HistoryRepository(reopened).progressFor(42, 12))?.position,
        const Duration(minutes: 20),
      );
      expect(
        (await PreferencesRepository(reopened).load()).preferredQualityHeight,
        720,
      );
      await reopened.close();
      await dir.delete(recursive: true);
    });
  });
}
